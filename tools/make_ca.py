#!/usr/bin/env python3
"""Write src/github_roots.h: the root certificates the remote trusts for GitHub.

    python3 tools/make_ca.py

The firmware checks GitHub's API (api.github.com) and downloads release files
(release-assets.githubusercontent.com) over HTTPS. This takes the roots those
chain to, plus their likely successors, from Mozilla's list as curl publishes it
(https://curl.se/docs/caextract.html). Run it again if updates start failing
with a certificate error.
"""

import pathlib
import re
import subprocess
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "github_roots.h"
BUNDLE = "https://curl.se/ca/cacert.pem"

# api.github.com: Sectigo E46, cross-signed by USERTrust ECC.
# release-assets.githubusercontent.com: ISRG Root YR, cross-signed by ISRG Root X1.
# The rest are those CAs' other current roots, and DigiCert's, which GitHub used before.
NAMES = [
    "USERTrust ECC Certification Authority",
    "USERTrust RSA Certification Authority",
    "Sectigo Public Server Authentication Root E46",
    "Sectigo Public Server Authentication Root R46",
    "ISRG Root X1",
    "ISRG Root X2",
    "DigiCert Global Root G2",
]


def main():
    pem = urllib.request.urlopen(BUNDLE, timeout=30).read().decode()
    certs = re.findall(r"-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----", pem, re.S)
    picked = {}
    for cert in certs:
        subject = subprocess.run(
            ["openssl", "x509", "-noout", "-subject", "-nameopt", "multiline"],
            input=cert,
            capture_output=True,
            text=True,
            check=True,
        ).stdout
        m = re.search(r"commonName\s*=\s*(.+)", subject)
        if m and m[1].strip() in NAMES:
            picked[m[1].strip()] = cert
    missing = [n for n in NAMES if n not in picked]
    if missing:
        raise SystemExit(f"not in {BUNDLE}: {', '.join(missing)}")

    body = "\n".join(f"// {name}\n" + "\n".join(f'"{line}\\n"' for line in picked[name].splitlines()) for name in NAMES)
    OUT.write_text(
        "// Generated by tools/make_ca.py from Mozilla's CA list (curl.se/ca/cacert.pem). Don't edit.\n"
        "// The roots the remote trusts for api.github.com and GitHub's release downloads.\n"
        "#pragma once\n\n"
        f"static const char kGithubRoots[] =\n{body};\n"
    )
    print(f"{OUT.relative_to(ROOT)}: {len(NAMES)} roots")


if __name__ == "__main__":
    main()
