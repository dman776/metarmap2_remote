#!/usr/bin/env python3
"""Turn the SVGs in assets/ into LVGL ARGB8888 images in src/: the logo and the update star, and the icons in
assets/icons/ into src/icons.c (icons.h declares them). The visualizers' icons in src/icons.c are 20x20 A8 alpha
masks instead, the Chart's own (assets/icon_masks.py, a copy of metarmap2's src/metarmap/web/icon_masks.py): the ones
built in, for when the Chart can't give them (icon_store.h); vis_icon() finds one by its name.

    python3 tools/make_images.py

Needs rsvg-convert (brew install librsvg). Run it again after changing an SVG, or after copying a newer
icon_masks.py from metarmap2.
"""

import hashlib
import importlib.util
import pathlib
import struct
import subprocess
import zlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
# assets/<svg> -> src/<name>.c, with an lv_image_dsc_t called <name>
IMAGES = [("logo.svg", "logo"), ("star.svg", "star_icon")]
# The visualizer icons built in: the Chart's masks for these. A newer one (hourglass, FAA Delays') isn't: the Copilot
# fetches it from the Chart (GET /api/icon/<name>) and saves it.
COMPILED = (
    "ban",
    "chase",
    "clock",
    "cloud",
    "compass",
    "droplet",
    "eye",
    "gauge",
    "gust",
    "mountain",
    "plane",
    "rain",
    "rainbow",
    "thermometer",
    "umbrella",
    "warning",
    "wind",
)
MASK_SIZE = 20


def read_png(data):
    """RGBA pixels of an 8-bit, non-interlaced RGBA PNG (what rsvg-convert writes)."""
    pos, idat = 8, b""
    while pos < len(data):
        (n,) = struct.unpack(">I", data[pos : pos + 4])
        kind, body = data[pos + 4 : pos + 8], data[pos + 8 : pos + 8 + n]
        if kind == b"IHDR":
            w, h, depth, color = struct.unpack(">IIBB", body[:10])
            if (depth, color) != (8, 6):
                raise SystemExit("expected an 8-bit RGBA PNG")
        elif kind == b"IDAT":
            idat += body
        pos += 12 + n
    raw, bpp, stride = zlib.decompress(idat), 4, w * 4
    out, prev = bytearray(), bytearray(stride)
    for y in range(h):
        f, line = raw[y * (stride + 1)], bytearray(raw[y * (stride + 1) + 1 : (y + 1) * (stride + 1)])
        for i in range(stride):
            a = line[i - bpp] if i >= bpp else 0
            b, c = prev[i], prev[i - bpp] if i >= bpp else 0
            if f == 1:
                line[i] = (line[i] + a) & 255
            elif f == 2:
                line[i] = (line[i] + b) & 255
            elif f == 3:
                line[i] = (line[i] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        out += line
        prev = line
    return w, h, bytes(out)


def argb_image(path):
    """An SVG as (w, h, LVGL ARGB8888 bytes: B, G, R, A in memory)."""
    png = subprocess.run(["rsvg-convert", str(path)], check=True, capture_output=True).stdout
    w, h, rgba = read_png(png)
    argb = bytearray()
    for i in range(0, len(rgba), 4):
        r, g, b, a = rgba[i : i + 4]
        argb += bytes((b, g, r, a))
    return w, h, argb


def image_c(name, w, h, argb, static="", cf="ARGB8888", bpp=4):
    rows = ",\n".join("    " + ", ".join(f"0x{v:02x}" for v in argb[i : i + 16]) for i in range(0, len(argb), 16))
    return f"""static const uint8_t {name}_data[] = {{
{rows}
}};

{static}const lv_image_dsc_t {name} = {{
    .header = {{
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = LV_COLOR_FORMAT_{cf},
        .w = {w},
        .h = {h},
        .stride = {w * bpp},
    }},
    .data_size = sizeof({name}_data),
    .data = {name}_data,
}};
"""


def write_image(svg, name):
    w, h, argb = argb_image(ROOT / "assets" / svg)
    out = ROOT / "src" / f"{name}.c"
    out.write_text(
        f"// Generated by tools/make_images.py from assets/{svg}. Don't edit.\n#include <lvgl.h>\n\n"
        + image_c(name, w, h, argb)
    )
    print(f"{out.relative_to(ROOT)}: {w}x{h}")


def chart_masks():
    """(MASKS, REV) of assets/icon_masks.py, each mask checked: 400 bytes, and its rev the start of its SHA-1."""
    spec = importlib.util.spec_from_file_location("icon_masks", ROOT / "assets" / "icon_masks.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    for name, mask in module.MASKS.items():
        if len(mask) != MASK_SIZE * MASK_SIZE:
            raise SystemExit(f"icon_masks.py: {name} is {len(mask)} bytes, not {MASK_SIZE * MASK_SIZE}")
        if hashlib.sha1(mask).hexdigest()[:8] != module.REV[name]:
            raise SystemExit(f"icon_masks.py: {name}'s rev isn't its mask's")
    return module.MASKS, module.REV


def write_icons():
    """assets/icons/<name>.svg -> icon_<name> in src/icons.c (ARGB8888), and the COMPILED visualizer icons as
    icon_vis_<name>, the Chart's A8 masks; vis_icon() finds those by name, vis_icon_rev() says which mask each is."""
    svgs = sorted((ROOT / "assets" / "icons").glob("*.svg"))
    masks, revs = chart_masks()
    missing = [icon for icon in COMPILED if icon not in masks]
    if missing:
        raise SystemExit(f"icon_masks.py has no {', '.join(missing)}")
    body = ""
    for svg in svgs:
        w, h, argb = argb_image(svg)
        body += "\n" + image_c("icon_" + svg.stem, w, h, argb)
    for icon in COMPILED:
        body += "\n" + image_c(f"icon_vis_{icon}", MASK_SIZE, MASK_SIZE, masks[icon], cf="A8", bpp=1)
    table = "\n".join(f'    {{"{icon}", "{revs[icon]}", &icon_vis_{icon}}},' for icon in COMPILED)
    (ROOT / "src" / "icons.c").write_text(
        "// Generated by tools/make_images.py from assets/icons/ and assets/icon_masks.py. Don't edit.\n"
        '#include <lvgl.h>\n#include <string.h>\n\n#include "icons.h"\n'
        + body
        + f"""
static const struct {{
  const char* name;
  const char* rev;
  const lv_image_dsc_t* image;
}} kVisIcons[] = {{
{table}
}};

const lv_image_dsc_t* vis_icon(const char* name) {{
  for (size_t i = 0; name && i < sizeof(kVisIcons) / sizeof(kVisIcons[0]); i++) {{
    if (strcmp(kVisIcons[i].name, name) == 0) return kVisIcons[i].image;
  }}
  return NULL;
}}

const char* vis_icon_rev(const char* name) {{
  for (size_t i = 0; name && i < sizeof(kVisIcons) / sizeof(kVisIcons[0]); i++) {{
    if (strcmp(kVisIcons[i].name, name) == 0) return kVisIcons[i].rev;
  }}
  return NULL;
}}
"""
    )
    decls = "\n".join(
        [f"extern const lv_image_dsc_t icon_{svg.stem};" for svg in svgs]
        + [f"extern const lv_image_dsc_t icon_vis_{icon};" for icon in COMPILED]
    )
    (ROOT / "src" / "icons.h").write_text(
        f"""// Generated by tools/make_images.py from assets/icons/ and assets/icon_masks.py. Don't edit.
// White icons (the UI recolors them), and the visualizers' built in by their icon name: 20x20 A8 masks, the Chart's
// (drawn in the image recolor color).
#pragma once

#include <lvgl.h>

#ifdef __cplusplus
extern "C" {{
#endif

{decls}

// A visualizer's built-in icon by the name the map sends (/api/status visualizers[].icon); NULL if it has none.
const lv_image_dsc_t* vis_icon(const char* name);
// Which of the Chart's masks that is (its iconRev, 8 hex digits); NULL for one it doesn't know.
const char* vis_icon_rev(const char* name);

#ifdef __cplusplus
}}

// The icon to show for a visualizer whose icon is `name`, the Chart's mask `rev` ("" from a Chart that doesn't say):
// one fetched from the Chart and saved (icon_store.h), else the built-in one, else NULL (the tile shows none, and the
// Copilot asks the Chart for it). Defined in icon_store_fs.cpp.
const lv_image_dsc_t* vis_icon(const char* name, const char* rev);
#endif
"""
    )
    print(f"src/icons.c: {len(svgs)} icons, {len(COMPILED)} visualizers' (A8)")


def main():
    for svg, name in IMAGES:
        write_image(svg, name)
    write_icons()


if __name__ == "__main__":
    main()
