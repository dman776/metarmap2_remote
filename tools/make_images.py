#!/usr/bin/env python3
"""Turn the SVGs in assets/ into LVGL ARGB8888 images in src/: the logo and the update star, and the icons in
assets/icons/ into src/icons.c (icons.h declares them; vis_icon() finds a visualizer's by its name).

    python3 tools/make_images.py

Needs rsvg-convert (brew install librsvg). Run it again after changing an SVG.
"""

import pathlib
import struct
import subprocess
import zlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
# assets/<svg> -> src/<name>.c, with an lv_image_dsc_t called <name>
IMAGES = [("logo.svg", "logo"), ("star.svg", "star_icon")]


def read_png(data):
    """RGBA pixels of an 8-bit, non-interlaced RGBA PNG (what rsvg-convert writes)."""
    pos, idat = 8, b""
    while pos < len(data):
        (n,) = struct.unpack(">I", data[pos : pos + 4])
        kind, body = data[pos + 4 : pos + 8], data[pos + 8 : pos + 8 + n]
        if kind == b"IHDR":
            w, h, depth, color = struct.unpack(">IIBB", body[:10])
            if (depth, color) != (8, 6):
                raise SystemExit("expected an 8-bit RGBA PNG")
        elif kind == b"IDAT":
            idat += body
        pos += 12 + n
    raw, bpp, stride = zlib.decompress(idat), 4, w * 4
    out, prev = bytearray(), bytearray(stride)
    for y in range(h):
        f, line = raw[y * (stride + 1)], bytearray(raw[y * (stride + 1) + 1 : (y + 1) * (stride + 1)])
        for i in range(stride):
            a = line[i - bpp] if i >= bpp else 0
            b, c = prev[i], prev[i - bpp] if i >= bpp else 0
            if f == 1:
                line[i] = (line[i] + a) & 255
            elif f == 2:
                line[i] = (line[i] + b) & 255
            elif f == 3:
                line[i] = (line[i] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        out += line
        prev = line
    return w, h, bytes(out)


def argb_image(path):
    """An SVG as (w, h, LVGL ARGB8888 bytes: B, G, R, A in memory)."""
    png = subprocess.run(["rsvg-convert", str(path)], check=True, capture_output=True).stdout
    w, h, rgba = read_png(png)
    argb = bytearray()
    for i in range(0, len(rgba), 4):
        r, g, b, a = rgba[i : i + 4]
        argb += bytes((b, g, r, a))
    return w, h, argb


def image_c(name, w, h, argb, static=""):
    rows = ",\n".join("    " + ", ".join(f"0x{v:02x}" for v in argb[i : i + 16]) for i in range(0, len(argb), 16))
    return f"""static const uint8_t {name}_data[] = {{
{rows}
}};

{static}const lv_image_dsc_t {name} = {{
    .header = {{
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = LV_COLOR_FORMAT_ARGB8888,
        .w = {w},
        .h = {h},
        .stride = {w * 4},
    }},
    .data_size = sizeof({name}_data),
    .data = {name}_data,
}};
"""


def write_image(svg, name):
    w, h, argb = argb_image(ROOT / "assets" / svg)
    out = ROOT / "src" / f"{name}.c"
    out.write_text(
        f"// Generated by tools/make_images.py from assets/{svg}. Don't edit.\n#include <lvgl.h>\n\n"
        + image_c(name, w, h, argb)
    )
    print(f"{out.relative_to(ROOT)}: {w}x{h}")


def write_icons():
    """assets/icons/<name>.svg -> icon_<name> in src/icons.c; vis_<icon>.svg are the visualizers' (vis_icon())."""
    svgs = sorted((ROOT / "assets" / "icons").glob("*.svg"))
    body, vis = "", []
    for svg in svgs:
        name = "icon_" + svg.stem
        w, h, argb = argb_image(svg)
        body += "\n" + image_c(name, w, h, argb)
        if svg.stem.startswith("vis_"):
            vis.append((svg.stem[4:], name))
    table = "\n".join(f'    {{"{icon}", &{name}}},' for icon, name in vis)
    (ROOT / "src" / "icons.c").write_text(
        "// Generated by tools/make_images.py from assets/icons/. Don't edit.\n"
        '#include <lvgl.h>\n#include <string.h>\n\n#include "icons.h"\n'
        + body
        + f"""
static const struct {{
  const char* name;
  const lv_image_dsc_t* image;
}} kVisIcons[] = {{
{table}
}};

const lv_image_dsc_t* vis_icon(const char* name) {{
  for (size_t i = 0; name && i < sizeof(kVisIcons) / sizeof(kVisIcons[0]); i++) {{
    if (strcmp(kVisIcons[i].name, name) == 0) return kVisIcons[i].image;
  }}
  return NULL;
}}
"""
    )
    decls = "\n".join(f"extern const lv_image_dsc_t icon_{svg.stem};" for svg in svgs)
    (ROOT / "src" / "icons.h").write_text(
        f"""// Generated by tools/make_images.py from assets/icons/. Don't edit.
// White icons (the UI recolors them; the rainbow keeps its colors), and the visualizers' by their icon name.
#pragma once

#include <lvgl.h>

#ifdef __cplusplus
extern "C" {{
#endif

{decls}

// A visualizer's icon by the name the map sends (/api/status visualizers[].icon); NULL for one it doesn't know.
const lv_image_dsc_t* vis_icon(const char* name);

#ifdef __cplusplus
}}
#endif
"""
    )
    print(f"src/icons.c: {len(svgs)} icons, {len(vis)} visualizers'")


def main():
    for svg, name in IMAGES:
        write_image(svg, name)
    write_icons()


if __name__ == "__main__":
    main()
