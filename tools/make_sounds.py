#!/usr/bin/env python3
"""Turn the MP3s in assets/sounds/ into 16 kHz mono 16-bit PCM in src/sounds.c (sounds.h declares them), the
rate the speaker is set up for (kAudioRate in audio.h). The firmware plays them with audio_play().

    python3 tools/make_sounds.py

Needs ffmpeg (brew install ffmpeg). Run it again after changing an MP3.
"""

import array
import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
RATE = 16000
# assets/sounds/<file> -> the C name in sounds.h
SOUNDS = [
    ("airplane-chime.mp3", "chime"),  # the Copilot has reached the Chart
    ("hi-pop.mp3", "hi_pop"),  # a visualizer left out of auto-rotate
    ("lo-pop.mp3", "lo_pop"),  # a visualizer put back
]


def pcm(path):
    """The MP3 as mono 16-bit samples at RATE (ffmpeg mixes the channels down and resamples)."""
    out = subprocess.run(
        ["ffmpeg", "-v", "error", "-i", str(path), "-ac", "1", "-ar", str(RATE), "-f", "s16le", "-"],
        check=True,
        capture_output=True,
    ).stdout
    samples = array.array("h")
    samples.frombytes(out)  # little-endian, as the ESP32 and this computer
    return samples


def main():
    body = ""
    for file, name in SOUNDS:
        samples = pcm(ROOT / "assets" / "sounds" / file)
        rows = [", ".join(str(s) for s in samples[i : i + 16]) for i in range(0, len(samples), 16)]
        data = ",\n    ".join(rows)
        body += f"static const int16_t {name}_data[] = {{\n    {data},\n}};\n"
        body += f"const Sound sound_{name} = {{{name}_data, {len(samples)}}};\n\n"
        print(f"{file}: {len(samples)} samples, {len(samples) / RATE:.2f} s, {len(samples) * 2} bytes")
    (ROOT / "src" / "sounds.c").write_text(
        "// Generated by tools/make_sounds.py from assets/sounds/. Don't edit.\n"
        '#include "sounds.h"\n\n' + body.rstrip() + "\n"
    )
    decls = "\n".join(f"extern const Sound sound_{name};" for _, name in SOUNDS)
    (ROOT / "src" / "sounds.h").write_text(
        f"""// Generated by tools/make_sounds.py from assets/sounds/. Don't edit.
// Short sounds for audio_play(): mono, 16-bit, kAudioRate (16 kHz), kept in flash.
#pragma once

#include <stddef.h>
#include <stdint.h>

#ifdef __cplusplus
extern "C" {{
#endif

typedef struct {{
  const int16_t* pcm;
  size_t frames;
}} Sound;

{decls}

#ifdef __cplusplus
}}
#endif
"""
    )


if __name__ == "__main__":
    main()
