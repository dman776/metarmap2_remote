"""PlatformIO pre-build script: the firmware's version from git, for the splash screen.

Writes include/firmware_version.h (git-ignored) with FIRMWARE_VERSION, only when it changes, so a new
commit rebuilds the one file that shows it. Versions follow metarmap2's: a release is a tag like
v26.11.05.

    v26.11.05                   at the tag
    v26.11.05+3 abc1234         3 commits after it
    abc1234                     no tag yet
    ... modified                with uncommitted changes
"""

import pathlib
import re
import subprocess

Import("env")  # noqa: F821  (SCons provides it)

root = pathlib.Path(env["PROJECT_DIR"])  # noqa: F821
header = root / "include" / "firmware_version.h"


def describe():
    try:
        out = subprocess.run(
            ["git", "describe", "--tags", "--always", "--dirty", "--abbrev=7"],
            cwd=root,
            check=True,
            capture_output=True,
            text=True,
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"
    dirty = out.endswith("-dirty")
    out = out.removesuffix("-dirty")
    m = re.fullmatch(r"(.+)-(\d+)-g([0-9a-f]+)", out)
    version = f"{m[1]}+{m[2]} {m[3]}" if m else out
    return version + (" modified" if dirty else "")


text = f'// Generated by tools/version.py. Don\'t edit.\n#pragma once\n#define FIRMWARE_VERSION "{describe()}"\n'
if not header.exists() or header.read_text() != text:
    header.write_text(text)
