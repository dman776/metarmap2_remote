"""PlatformIO pre-build script: the firmware's version from git, for the splash and update screens.

Writes include/firmware_version.h (git-ignored), only when it changes, so a new commit rebuilds just the
files that use it:

    FIRMWARE_VERSION   what the screens show:
                         v26.11.05                   at a release tag
                         v26.11.05+3 abc1234         3 commits after it
                         abc1234                     before the first release
                         ... modified                with uncommitted changes
    FIRMWARE_TAG       the release it's at or after ("" before the first)
    FIRMWARE_COMMIT    the commit, 7 characters

Releases are tags like v26.11.05, as metarmap2's. CI's build-<branch> tags (the Latest commit and Branch
update channels) aren't releases, so they're left out.
"""

import pathlib
import re
import subprocess

Import("env")  # noqa: F821  (SCons provides it)

root = pathlib.Path(env["PROJECT_DIR"])  # noqa: F821
header = root / "include" / "firmware_version.h"
RELEASE_TAGS = "v[0-9]*"


def git(*args):
    try:
        return subprocess.run(["git", *args], cwd=root, check=True, capture_output=True, text=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return ""


def version():
    out = git("describe", "--tags", "--match", RELEASE_TAGS, "--always", "--dirty", "--abbrev=7")
    if not out:
        return "unknown"
    dirty = out.endswith("-dirty")
    out = out.removesuffix("-dirty")
    m = re.fullmatch(r"(.+)-(\d+)-g([0-9a-f]+)", out)
    return (f"{m[1]}+{m[2]} {m[3]}" if m else out) + (" modified" if dirty else "")


text = (
    "// Generated by tools/version.py. Don't edit.\n"
    "#pragma once\n"
    f'#define FIRMWARE_VERSION "{version()}"\n'
    f'#define FIRMWARE_TAG "{git("describe", "--tags", "--match", RELEASE_TAGS, "--abbrev=0")}"\n'
    f'#define FIRMWARE_COMMIT "{git("rev-parse", "--short=7", "HEAD")}"\n'
)
if not header.exists() or header.read_text() != text:
    header.write_text(text)
